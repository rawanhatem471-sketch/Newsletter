function shareNews(title) {

    if (navigator.share) {

        navigator.share({

            title: "ELPAI",

            text: title

        });

    } else {

        navigator.clipboard
            .writeText(title)
            .then(() => {

                alert(
                    "تم نسخ عنوان الخبر"
                );

            });

    }

}


