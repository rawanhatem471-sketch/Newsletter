/* =========================================================
   CREATE SECTION
========================================================= */

function createSection(
    section,
    newsletterId,
    newsletterTitle
) {

    let html = `

        <section class="news-section">

            <div class="section-heading">

                <span class="section-line"></span>

                <h3>
                    ${section.title}
                </h3>

            </div>

    `;


    /* EMPTY */

    if (section.empty) {

        html += `

            <div class="empty-state">

                <div class="empty-icon">
                    ○
                </div>

                <strong>
                    لا توجد نتائج في هذا القسم حالياً
                </strong>

                <span>
                    سيتم عرض المحتوى هنا عند توفره.
                </span>

            </div>

        `;

        return html +
            `</section>`;

    }


    /* FEATURED */

    if (section.featured) {

        html += createCard(
            section.featured,
            true,
            newsletterId,
            newsletterTitle
        );


        if (section.cards) {

            html += `

                <div class="news-grid">

                    ${section.cards
                        .map(
                            card =>
                                createCard(
                                    card,
                                    false,
                                    newsletterId,
                                    newsletterTitle
                                )
                        )
                        .join("")}

                </div>

            `;

        }

    }


    /* COUNTRIES */

    if (section.countries) {

        section.countries
            .forEach(country => {

                html += `

                    <div class="country-heading">

                        <span class="country-icon">
                            ${country.code}
                        </span>

                        <h4>
                            ${country.name}
                        </h4>

                    </div>


                    <div class="news-grid">

                        ${country.cards
                            .map(
                                card =>
                                    createCard(
                                        card,
                                        false,
                                        newsletterId,
                                        newsletterTitle
                                    )
                            )
                            .join("")}

                    </div>

                `;

            });

    }


    /* NORMAL CARDS */

    if (
        !section.featured &&
        !section.countries &&
        section.cards
    ) {

        html += `

            <div class="news-grid">

                ${section.cards
                    .map(
                        card =>
                            createCard(
                                card,
                                false,
                                newsletterId,
                                newsletterTitle
                            )
                    )
                    .join("")}

            </div>

        `;

    }


    html += `</section>`;


    return html;

}


