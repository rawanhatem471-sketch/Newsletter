/* =========================================================
   SHARE
========================================================= */

function shareNews(title) {

    if (navigator.share) {

        navigator.share({

            title: "ELPAI",

            text: title

        });

    }

    else {

        navigator.clipboard
            .writeText(title)
            .then(() => {

                alert("تم نسخ عنوان الخبر");

            });

    }

}


/* =========================================================
   CREATE CARD
========================================================= */

function createCard(news, featured = false) {

    return `

        <article class="${featured ? "featured-news" : "news-card"}">

            <div class="news-meta">

                <span class="news-dot"></span>

                ${featured ? "خبر رئيسي" : "مستجد قانوني"}

            </div>


            <h4>
                ${news.title}
            </h4>


            <p>
                ${news.text}
            </p>


            <div class="news-actions">

                <button
                    class="share-button"
                    onclick="shareNews(${JSON.stringify(news.title)})">

                    مشاركة الآن ↗

                </button>

            </div>

        </article>

    `;

}


/* =========================================================
   CREATE SECTION
========================================================= */

function createSection(section) {

    let html = `

        <section class="news-section">

            <div class="section-heading">

                <span class="section-line"></span>

                <h3>
                    ${section.title}
                </h3>

            </div>

    `;


    /* EMPTY */

    if (section.empty) {

        html += `

            <div class="empty-state">

                <div class="empty-icon">
                    ○
                </div>

                <strong>
                    لا توجد نتائج في هذا القسم حالياً
                </strong>

                <span>
                    سيتم عرض المحتوى هنا عند توفره.
                </span>

            </div>

        `;

        html += `</section>`;

        return html;

    }


    /* FEATURED */

    if (section.featured) {

        html += createCard(
            section.featured,
            true
        );


        if (section.cards) {

            html += `

                <div class="news-grid">

                    ${section.cards
                        .map(card => createCard(card))
                        .join("")}

                </div>

            `;

        }

    }


    /* COUNTRIES */

    if (section.countries) {

        section.countries.forEach(country => {

            html += `

                <div class="country-heading">

                    <span class="country-icon">

                        ${country.code}

                    </span>

                    <h4>
                        ${country.name}
                    </h4>

                </div>


                <div class="news-grid">

                    ${country.cards
                        .map(card => createCard(card))
                        .join("")}

                </div>

            `;

        });

    }


    /* NORMAL CARDS */

    if (!section.featured && !section.countries && section.cards) {

        html += `

            <div class="news-grid">

                ${section.cards
                    .map(card => createCard(card))
                    .join("")}

            </div>

        `;

    }


    html += `</section>`;

    return html;

}


/* =========================================================
   CREATE NEWSLETTER
========================================================= */

function renderNewsletter(newsletter) {

    document
        .getElementById("issueType")
        .textContent = newsletter.type;


    document
        .getElementById("issueTitle")
        .textContent = newsletter.title;


    document
        .getElementById("issueNumber")
        .textContent = newsletter.number;


    let content = `

        <section class="newsletter-intro">

            <h3>
                المقدمة
            </h3>

            <p>
                ${newsletter.intro}
            </p>


            <div class="highlights">

    `;


    newsletter.highlights.forEach((item, index) => {

        content += `

            <div class="highlight">

                <span class="highlight-number">

                    ${String(index + 1).padStart(2, "0")}

                </span>

                ${item}

            </div>

        `;

    });


    content += `

            </div>

        </section>

    `;


    newsletter.sections.forEach(section => {

        content += createSection(section);

    });


    document
        .getElementById("newsletterContent")
        .innerHTML = content;

}


/* =========================================================
   TABS
========================================================= */

const tabs =
    document.querySelectorAll(
        ".newsletter-tab:not(.disabled)"
    );


tabs.forEach(tab => {

    tab.addEventListener(
        "click",
        () => {

            tabs.forEach(item => {

                item.classList.remove("active");

            });


            tab.classList.add("active");


            const selected =
                tab.dataset.newsletter;


            if (selected === "arab") {

                renderNewsletter(
                    arabNewsletter
                );

            }

            else {

                renderNewsletter(
                    egyptNewsletter
                );

            }


            document
                .querySelector(".newsletter-container")
                .scrollIntoView({

                    behavior: "smooth",

                    block: "start"

                });

        }
    );

});


