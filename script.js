function renderArchive(
    type = "egypt"
) {

    const archive =
        document.getElementById(
            "newsletterArchive"
        );


    if (!archive) return;


    const filtered =
        newsletters.filter(
            newsletter =>
                newsletter.type === type
        );


    /* ARCHIVE TITLE */

    const archiveTitle =
        document.getElementById(
            "archiveTitle"
        );


    if (archiveTitle) {

        archiveTitle.textContent =
            type === "egypt"
                ? "أعداد النشرة المصرية"
                : "أعداد النشرة العربية";

    }


    /* ARCHIVE TYPE */

    const archiveType =
        document.getElementById(
            "archiveType"
        );


    if (archiveType) {

        archiveType.textContent =
            type === "egypt"
                ? "النشرة المصرية"
                : "النشرة العربية";

    }


    /* ARCHIVE COUNT */

    const archiveCount =
        document.getElementById(
            "archiveCount"
        );


    if (archiveCount) {

        archiveCount.textContent =
            type === "egypt"
                ? `${filtered.length} نشرة`
                : `${filtered.length} أعداد`;

    }


    /* EMPTY */

    if (!filtered.length) {

        archive.innerHTML = `

            <div class="archive-empty">

                <strong>
                    لا توجد نشرات متاحة حالياً
                </strong>

                <span>
                    سيتم إضافة الأعداد الجديدة هنا عند توفرها.
                </span>

            </div>

        `;

        return;

    }


    /* RENDER */

    archive.innerHTML =
        filtered
            .map(createArchiveCard)
            .join("");

}


