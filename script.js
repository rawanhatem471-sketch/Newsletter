/* =========================================================
   SAVED ARTICLES
========================================================= */

const SAVED_KEY = "elpai_saved_articles";


function getSavedArticles() {

    try {

        const saved =
            localStorage.getItem(SAVED_KEY);

        return saved
            ? JSON.parse(saved)
            : [];

    } catch (error) {

        return [];

    }

}


function saveSavedArticles(items) {

    localStorage.setItem(
        SAVED_KEY,
        JSON.stringify(items)
    );

}


function articleKey(
    newsletterId,
    title
) {

    return newsletterId + "::" + title;

}


function isArticleSaved(
    newsletterId,
    title
) {

    return getSavedArticles().some(
        article =>
            article.id ===
            articleKey(
                newsletterId,
                title
            )
    );

}


/* =========================================================
   SAVE / REMOVE ARTICLE
========================================================= */

function toggleSaveArticle(
    article,
    newsletterId,
    newsletterTitle
) {

    const saved =
        getSavedArticles();

    const id =
        articleKey(
            newsletterId,
            article.title
        );

    const existingIndex =
        saved.findIndex(
            item =>
                item.id === id
        );


    if (existingIndex !== -1) {

        saved.splice(
            existingIndex,
            1
        );

    } else {

        saved.push({

            id: id,

            title:
                article.title,

            text:
                article.text,

            newsletterId:
                newsletterId,

            newsletterTitle:
                newsletterTitle

        });

    }


    saveSavedArticles(saved);

    updateSaveButtons();

    renderSavedArticles();

}


/* =========================================================
   UPDATE SAVE BUTTONS
========================================================= */

function updateSaveButtons() {

    document
        .querySelectorAll(".save-button")
        .forEach(button => {

            const newsletterId =
                button.dataset.newsletter;

            const title =
                button.dataset.title;

            const saved =
                isArticleSaved(
                    newsletterId,
                    title
                );


            button.classList.toggle(
                "saved",
                saved
            );


            button.textContent =
                saved
                    ? "✓ محفوظ"
                    : "♡ حفظ";

        });

}


/* =========================================================
   GET NEWSLETTER ID
========================================================= */

function getNewsletterId() {

    const params =
        new URLSearchParams(
            window.location.search
        );

    return params.get("id");

}


/* =========================================================
   SHARE
========================================================= */

function shareNews(title) {

    if (
        navigator.share
    ) {

        navigator.share({

            title: "ELPAI",

            text: title

        }).catch(() => {});

    } else if (
        navigator.clipboard
    ) {

        navigator.clipboard
            .writeText(title)
            .then(() => {

                alert(
                    "تم نسخ عنوان الخبر"
                );

            })
            .catch(() => {

                alert(
                    "تعذر نسخ العنوان"
                );

            });

    } else {

        alert(
            title
        );

    }

}


/* =========================================================
   CREATE NEWS CARD
========================================================= */

function createCard(
    news,
    featured = false,
    newsletterId = "",
    newsletterTitle = ""
) {

    const saved =
        isArticleSaved(
            newsletterId,
            news.title
        );


    const article =
        document.createElement(
            "article"
        );


    article.className =
        featured
            ? "featured-news"
            : "news-card";


    const meta =
        document.createElement(
            "div"
        );

    meta.className =
        "news-meta";


    const dot =
        document.createElement(
            "span"
        );

    dot.className =
        "news-dot";


    meta.appendChild(dot);


    const metaText =
        document.createTextNode(
            featured
                ? "خبر رئيسي"
                : "مستجد قانوني"
        );


    meta.appendChild(
        metaText
    );


    const heading =
        document.createElement(
            "h4"
        );

    heading.textContent =
        news.title;


    const paragraph =
        document.createElement(
            "p"
        );

    paragraph.textContent =
        news.text;


    const actions =
        document.createElement(
            "div"
        );

    actions.className =
        "news-actions";


    const saveButton =
        document.createElement(
            "button"
        );

    saveButton.type =
        "button";

    saveButton.className =
        "save-button" +
        (saved ? " saved" : "");

    saveButton.dataset.newsletter =
        newsletterId;

    saveButton.dataset.title =
        news.title;

    saveButton.textContent =
        saved
            ? "✓ محفوظ"
            : "♡ حفظ";


    saveButton.addEventListener(
        "click",
        function () {

            toggleSaveArticle(
                news,
                newsletterId,
                newsletterTitle
            );

        }
    );


    const shareButton =
        document.createElement(
            "button"
        );

    shareButton.type =
        "button";

    shareButton.className =
        "share-button";

    shareButton.textContent =
        "مشاركة الآن ↗";


    shareButton.addEventListener(
        "click",
        function () {

            shareNews(
                news.title
            );

        }
    );


    actions.appendChild(
        saveButton
    );

    actions.appendChild(
        shareButton
    );


    article.appendChild(
        meta
    );

    article.appendChild(
        heading
    );

    article.appendChild(
        paragraph
    );

    article.appendChild(
        actions
    );


    return article;

}


/* =========================================================
   CREATE SECTION
========================================================= */

function createSection(
    section,
    newsletterId,
    newsletterTitle
) {

    const sectionElement =
        document.createElement(
            "section"
        );


    sectionElement.className =
        "news-section";


    /* SECTION HEADING */

    const heading =
        document.createElement(
            "div"
        );

    heading.className =
        "section-heading";


    const line =
        document.createElement(
            "span"
        );

    line.className =
        "section-line";


    const title =
        document.createElement(
            "h3"
        );

    title.textContent =
        section.title;


    heading.appendChild(
        line
    );

    heading.appendChild(
        title
    );


    sectionElement.appendChild(
        heading
    );


    /* EMPTY */

    if (section.empty) {

        const empty =
            document.createElement(
                "div"
            );

        empty.className =
            "empty-state";


        const icon =
            document.createElement(
                "div"
            );

        icon.className =
            "empty-icon";

        icon.textContent =
            "○";


        const strong =
            document.createElement(
                "strong"
            );

        strong.textContent =
            "لا توجد نتائج في هذا القسم حالياً";


        const span =
            document.createElement(
                "span"
            );

        span.textContent =
            "سيتم عرض المحتوى هنا عند توفره.";


        empty.appendChild(
            icon
        );

        empty.appendChild(
            strong
        );

        empty.appendChild(
            span
        );


        sectionElement.appendChild(
            empty
        );


        return sectionElement;

    }


    /* FEATURED */

    if (section.featured) {

        sectionElement.appendChild(

            createCard(
                section.featured,
                true,
                newsletterId,
                newsletterTitle
            )

        );


        if (
            section.cards &&
            section.cards.length
        ) {

            const grid =
                document.createElement(
                    "div"
                );

            grid.className =
                "news-grid";


            section.cards.forEach(
                card => {

                    grid.appendChild(

                        createCard(
                            card,
                            false,
                            newsletterId,
                            newsletterTitle
                        )

                    );

                }
            );


            sectionElement.appendChild(
                grid
            );

        }

    }


    /* COUNTRIES */

    if (section.countries) {

        section.countries.forEach(
            country => {

                const countryHeading =
                    document.createElement(
                        "div"
                    );

                countryHeading.className =
                    "country-heading";


                const countryIcon =
                    document.createElement(
                        "span"
                    );

                countryIcon.className =
                    "country-icon";

                countryIcon.textContent =
                    country.code;


                const countryName =
                    document.createElement(
                        "h4"
                    );

                countryName.textContent =
                    country.name;


                countryHeading.appendChild(
                    countryIcon
                );

                countryHeading.appendChild(
                    countryName
                );


                sectionElement.appendChild(
                    countryHeading
                );


                const grid =
                    document.createElement(
                        "div"
                    );

                grid.className =
                    "news-grid";


                country.cards.forEach(
                    card => {

                        grid.appendChild(

                            createCard(
                                card,
                                false,
                                newsletterId,
                                newsletterTitle
                            )

                        );

                    }
                );


                sectionElement.appendChild(
                    grid
                );

            }
        );

    }


    /* NORMAL CARDS */

    if (
        !section.featured &&
        !section.countries &&
        section.cards
    ) {

        const grid =
            document.createElement(
                "div"
            );

        grid.className =
            "news-grid";


        section.cards.forEach(
            card => {

                grid.appendChild(

                    createCard(
                        card,
                        false,
                        newsletterId,
                        newsletterTitle
                    )

                );

            }
        );


        sectionElement.appendChild(
            grid
        );

    }


    return sectionElement;

}


